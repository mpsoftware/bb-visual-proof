const TEXT: Record<Locale, Text> = { de, en };

/** The `language` setting wins; `auto` takes the first supported browser or page language, else English. */
export function resolveLocale(setting: unknown, languages: readonly (string | undefined)[]): Locale {
  if (setting === "en" || setting === "de") return setting;
  for (const language of languages) {
    const primary = language?.toLowerCase().split("-")[0];
    if (primary === "en" || primary === "de") return primary;
  }
  return "en";
}

/**
 * The browser's preferred languages come first: BB ships its UI in English only, so the page language carries no
 * user choice today and is the fallback.
 */
function browserLanguages(): Array<string | undefined> {
  if (typeof navigator === "undefined") return [];
  return [...(navigator.languages ?? []), navigator.language, typeof document === "undefined" ? undefined : document.documentElement.lang];
}

export type I18n = { locale: Locale; t: Text };

/** The panel's locale and strings; follows a changed `language` setting without a reload. */
export function useText(): I18n {
  const locale = resolveLocale(useSettings().values?.language, browserLanguages());
  return { locale, t: TEXT[locale] };
}
